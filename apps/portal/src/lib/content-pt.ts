/** HubSpot stage DISPLAY in PT; keeps an optional "(N)" count suffix (chart bars)
   intact so the same map serves the summary chart and the deal-record chips. */
export function stageName(locale: string, label: string): string {
  if (locale !== "pt" || !label) return label;
  const m = label.match(/^(.+?)\s*\((\d+)\)$/);
  if (m && STAGE_PT[m[1]]) return `${STAGE_PT[m[1]]} (${m[2]})`;
  return STAGE_PT[label] ?? label;
}

/* ---- CRM traffic sources inside deal records (Fidv3 N1) — same technique. Keyed
   lowercase; matches a whole cell (peek "Organic search") or an embedded segment
   ("... · organic search"), preserving the source casing. "email marketing" stays
   EN (native anglicism). ---- */
export const SOURCE_PT: Record<string, string> = {
  "organic search": "busca orgânica",
  "organic social": "social orgânico",
  "paid social": "social pago",
  "direct traffic": "tráfego direto",
  "referrals": "indicações",
};
const SOURCE_RE = /\b(organic search|organic social|paid social|direct traffic|referrals)\b/gi;
export function sourceName(locale: string, text: string): string {
  if (locale !== "pt" || !text) return text;
  return text.replace(SOURCE_RE, (m) => {
    const pt = SOURCE_PT[m.toLowerCase()];
    return pt ? matchLead(m, pt) : m;
  });
}

