/** department DISPLAY name: PT when locale=pt, else the EN name.
   Shared by the chart AND every map surface (macro labels, dive serif,
   bottom nav, edge buttons, drawer crumb, topbar search). */
export function deptName(locale: string, name: string): string {
  return locale === "pt" ? DEPT_PT[name] ?? name : name;
}

/** job DISPLAY name in the CHART: PT when locale=pt, else the EN name. */
export function jobName(locale: string, name: string): string {
  if (SOLUTION_RENAME[name]) return SOLUTION_RENAME[name];
  return locale === "pt" ? JOB_NAME_PT[name] ?? name : name;
}

