/** localize the month token in an axis label ("May 15" → "mai 15", "Aug" → "ago")
   when locale=pt; day numbers / anchors are untouched. EN keeps the source. */
export function axisMonths(locale: string, label: string): string {
  if (locale !== "pt") return label;
  return label.replace(/\b(Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Oct|Nov|Dec)\b/g, (m) => MONTH_ABBR_PT[m] ?? m);
}

/** keep the source's leading capitalization when swapping in the PT term. */
function matchLead(src: string, pt: string): string {
  const c = src.charAt(0);
  return c !== c.toLowerCase() && c === c.toUpperCase() ? pt.charAt(0).toUpperCase() + pt.slice(1) : pt;
}

