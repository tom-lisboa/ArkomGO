/* ---- demo-string formatters ("2 installs" / "3 days ago" / "Wednesday") ---- */
export function installsPt(en: string): string {
  const m = en.match(/^(\d+)\s+install/);
  if (!m) return en;
  const n = +m[1];
  return `${n} ${n === 1 ? "instalação" : "instalações"}`;
}
export function timeAgoPt(en: string): string {
  const m = en.match(/^(\d+)\s+days?\s+ago$/);
  if (m) return `há ${m[1]} dia${m[1] === "1" ? "" : "s"}`;
  return en;
}
