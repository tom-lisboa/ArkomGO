/** PT version of chart-matrix howToRun (same composition, translated). */
export function howToRunPt(jobName: string, deptName: string, fnName: string, nSkills: number, tools: string[], level: string): string {
  const skillsPart = nSkills > 0 ? `${nSkills} arquivo${nSkills === 1 ? "" : "s"} de skill` : "nenhum arquivo de skill dedicado ainda";
  const toolsPart = tools.length > 0 ? `, conectado a ${tools.join(", ")}` : "";
  const mode = level === "autonomous" ? "totalmente sem supervisão" : level === "assisted" ? "rascunhando para um humano aprovar" : "como uma jogada conduzida por humano";
  return `Acione a skill ${jobName} pelo ramo ${deptName} · ${fnName}. Ela roda ${skillsPart}${toolsPart}, ${mode}.`;
}

